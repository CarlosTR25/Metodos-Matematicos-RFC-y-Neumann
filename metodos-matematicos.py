from scipy.special import yv

x = np.linspace(0.01, 20, 1000)

# Funciones de Neumann N0, N1 y N2
N0 = yv(0, x)
N1 = yv(1, x)
N2 = yv(2, x)

# Gráfica
plt.figure(figsize=(8, 5))

plt.plot(x, N0, label=r'$N_0(x)$')
plt.plot(x, N1, label=r'$N_1(x)$')
plt.plot(x, N2, label=r'$N_2(x)$')

plt.axhline(0, color='black', linewidth=0.8)

plt.xlabel(r'$x$')
plt.ylabel(r'$N_n(x)$')
plt.title('Funciones de Neumann')
plt.legend()
plt.grid(True)

plt.ylim(-2, 1)

plt.savefig('neumann.png', dpi=300, bbox_inches='tight')

plt.show()