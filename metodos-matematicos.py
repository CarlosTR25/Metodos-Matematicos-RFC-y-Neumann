import numpy as np
import matplotlib.pyplot as plt
from scipy.special import sph_harm

theta = np.linspace(0, np.pi, 300)
phi = np.linspace(0, 2*np.pi, 300)

theta, phi = np.meshgrid(theta, phi)

l = 2
m = 0

# Armónico esférico
Y = sph_harm(m, l, phi, theta).real

# Gráfica
plt.figure(figsize=(9, 4.5))

plt.contourf(phi, theta, Y, levels=100)
plt.colorbar(label=r'$Y_{\ell m}(\theta,\phi)$')

plt.xlabel(r'$\phi$')
plt.ylabel(r'$\theta$')
plt.title(r'Patrón dominado por multipolos bajos: $\ell=2$, $m=0$')

plt.xticks(
    [0, np.pi/2, np.pi, 3*np.pi/2, 2*np.pi],
    [r'$0$', r'$\pi/2$', r'$\pi$', r'$3\pi/2$', r'$2\pi$']
)

plt.yticks(
    [0, np.pi/4, np.pi/2, 3*np.pi/4, np.pi],
    [r'$0$', r'$\pi/4$', r'$\pi/2$', r'$3\pi/4$', r'$\pi$']
)

plt.savefig('armonicos_bajos.png', dpi=300, bbox_inches='tight')

plt.show()

